function changerLangue(langue) {
  const t = TEXTES[langue];
  document.documentElement.lang = langue;
  document.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t[el.dataset.t]; });
  ["href", "alt", "aria-label"].forEach((attr) => {
    document.querySelectorAll(`[data-t-${attr}]`).forEach((el) => {
      el.setAttribute(attr, t[el.getAttribute(`data-t-${attr}`)]);
    });
  });
  document.querySelectorAll(".lang-btn").forEach((b) => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === langue));
  });
}

document.querySelectorAll(".lang-btn").forEach((b) => {
  b.addEventListener("click", () => changerLangue(b.dataset.lang));
});
